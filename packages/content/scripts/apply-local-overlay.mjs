#!/usr/bin/env node
// Layers extension-owned content (local/, see local/README.md) on top of the
// vendored upstream tree in assets/open-design/. Run automatically at the end
// of sync-open-design-content.mjs, and standalone (`npm run apply-overlay`)
// to refresh the overlay without re-cloning upstream. Idempotent.
//
// Upstream files are never modified: an overlay skill (or a new,
// no-upstream-counterpart design system) whose id collides with an upstream
// entry fails loudly instead of shadowing it. Each copied overlay dir
// carries an OVERLAY_MARKER file, so a standalone re-run can tell "our
// previous copy" (safe to replace/remove) apart from "an upstream entry
// that now has the same id" (a collision).
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { DESIGN_SECTIONS_FILE, applyDesignSections, splitSections } from './designSystemConsistency.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(__dirname, '..');
export const LOCAL_ROOT = path.join(packageRoot, 'local');
export const OVERLAY_MARKER = '.od-local-overlay';
/** The surface catalog (openspec add-surface-picker): local/surfaces.json, copied to the assets root. */
export const SURFACES_FILE = 'surfaces.json';
export const VOICE_FILE = 'voice.md';
/** Card and sticker printers' file requirements (openspec add-print-house-images). */
export const PRINT_HOUSES_FILE = 'print-houses.json';
/** Trusted third-party MCP servers (openspec add-integration-registry): local/integrations.json, copied to the assets root. */
export const INTEGRATIONS_FILE = 'integrations.json';
/** Curated design-system descriptors (openspec add-design-system-matching): local/design-system-descriptors.json, copied to the assets root. */
export const DESCRIPTORS_FILE = 'design-system-descriptors.json';
/** The public gallery's address and switch (openspec link-public-gallery): local/gallery-site.json, copied to the assets root. */
export const GALLERY_SITE_FILE = 'gallery-site.json';
/** Third-party licence notices for ported content (openspec add-mobile-design-systems): local/notices/*, copied to the assets' notices/. */
export const NOTICES_DIR = 'notices';
/** Kit-owned craft docs (openspec add-states-and-microcopy-craft): local/craft/<id>.md, copied beside upstream's craft/ docs, never over one. */
export const CRAFT_DIR = 'craft';
/** Extra craft docs per skill or template id, merged into od.craft.requires at load: local/craft-requires.json, copied to the assets root. */
export const CRAFT_REQUIRES_FILE = 'craft-requires.json';
// The files an overlay may contribute to an EXISTING upstream design system,
// either or both: additive token overrides, applied on top of (never instead
// of) the vendored tokens.css by core's resolveDesignSystemTokens(); and
// replacement DESIGN.md sections, applied to the loaded body by core's
// content index (openspec reconcile-design-system-sources). Both are
// generated by audit-design-system-consistency.mjs from
// local/design-system-sources.json.
export const TOKENS_OVERRIDE_FILE = 'tokens.override.css';
export { DESIGN_SECTIONS_FILE };
export const OVERRIDE_FILES = [TOKENS_OVERRIDE_FILE, DESIGN_SECTIONS_FILE];
// The files a NEW design system (one with no upstream counterpart) must
// contain — same v1 manifest shape as every bundled entry (manifest.json +
// DESIGN.md + tokens.css; see design-systems/README.md upstream). Which of
// the two shapes a given local/design-systems/<id>/ directory is using is
// inferred purely from its own file set (see applyLocalOverlay): one or both
// of OVERRIDE_FILES is an override, exactly these three is a new package —
// never both, never a partial set of either.
export const NEW_DESIGN_SYSTEM_FILES = ['DESIGN.md', 'manifest.json', 'tokens.css'];

async function pathExists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function listDirs(dir) {
  if (!(await pathExists(dir))) return [];
  return (await fs.readdir(dir, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name);
}

function isOverrideShape(names) {
  return names.size > 0 && [...names].every((name) => OVERRIDE_FILES.includes(name));
}

async function listFiles(dir) {
  if (!(await pathExists(dir))) return [];
  return (await fs.readdir(dir, { withFileTypes: true })).filter((e) => e.isFile()).map((e) => e.name);
}

async function listLocalCraft(localRoot) {
  return (await listFiles(path.join(localRoot, CRAFT_DIR))).filter((name) => name.endsWith('.md'));
}

// craft/ is a flat folder of upstream files, so the overlay can't mark each
// copy with its own OVERLAY_MARKER; instead one marker file in craft/ lists
// the names the previous run copied.
async function previousCraftCopies(targetRoot) {
  const marker = path.join(targetRoot, CRAFT_DIR, OVERLAY_MARKER);
  if (!(await pathExists(marker))) return new Set();
  return new Set((await fs.readFile(marker, 'utf8')).split('\n').filter((line) => line.endsWith('.md')));
}

/**
 * Every source file the overlay contributes, as { src, dst } pairs relative to
 * (localRoot, targetRoot). Shared with check-content-sync.mjs so the check
 * verifies exactly what this script writes.
 */
export async function listOverlayFiles(localRoot = LOCAL_ROOT) {
  const files = [];
  async function walk(relDir) {
    const abs = path.join(localRoot, relDir);
    for (const entry of await fs.readdir(abs, { withFileTypes: true })) {
      const rel = path.join(relDir, entry.name);
      if (entry.isDirectory()) await walk(rel);
      else if (entry.isFile()) files.push(rel);
    }
  }
  for (const id of await listDirs(path.join(localRoot, 'skills'))) await walk(path.join('skills', id));
  for (const id of await listDirs(path.join(localRoot, 'examples'))) await walk(path.join('examples', id));
  for (const name of await listFiles(path.join(localRoot, 'prompts'))) files.push(path.join('prompts', name));
  for (const name of await listFiles(path.join(localRoot, NOTICES_DIR))) files.push(path.join(NOTICES_DIR, name));
  for (const name of await listLocalCraft(localRoot)) files.push(path.join(CRAFT_DIR, name));
  if (await pathExists(path.join(localRoot, CRAFT_REQUIRES_FILE))) files.push(CRAFT_REQUIRES_FILE);
  if (await pathExists(path.join(localRoot, SURFACES_FILE))) files.push(SURFACES_FILE);
  if (await pathExists(path.join(localRoot, VOICE_FILE))) files.push(VOICE_FILE);
  if (await pathExists(path.join(localRoot, PRINT_HOUSES_FILE))) files.push(PRINT_HOUSES_FILE);
  if (await pathExists(path.join(localRoot, INTEGRATIONS_FILE))) files.push(INTEGRATIONS_FILE);
  if (await pathExists(path.join(localRoot, DESCRIPTORS_FILE))) files.push(DESCRIPTORS_FILE);
  if (await pathExists(path.join(localRoot, GALLERY_SITE_FILE))) files.push(GALLERY_SITE_FILE);
  for (const id of await listDirs(path.join(localRoot, 'design-systems'))) {
    const names = new Set(await listFiles(path.join(localRoot, 'design-systems', id)));
    if (isOverrideShape(names)) {
      for (const name of OVERRIDE_FILES) if (names.has(name)) files.push(path.join('design-systems', id, name));
    } else {
      for (const name of NEW_DESIGN_SYSTEM_FILES) files.push(path.join('design-systems', id, name));
    }
  }
  return files;
}

/** `--name: value;` declarations in a CSS text, last one wins (same regex upstream's asset generator uses). */
export function parseCssCustomProperties(css) {
  const out = new Map();
  for (const match of css.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[a-zA-Z0-9_-]+)\s*:\s*([^;]+);/g)) {
    out.set(match[1], match[2].trim().replace(/\s+/g, ' '));
  }
  return out;
}

/**
 * Override declarations whose value the vendored upstream tokens.css now
 * already has — i.e. upstream fixed it and the override can be deleted.
 * Returns `<id>: --name` strings.
 */
export async function findRedundantOverrides(targetRoot, localRoot = LOCAL_ROOT) {
  const redundant = [];
  for (const id of await listDirs(path.join(localRoot, 'design-systems'))) {
    // Skip new-package entries (no TOKENS_OVERRIDE_FILE to speak of) — this
    // check only applies to the override shape.
    if (!(await pathExists(path.join(localRoot, 'design-systems', id, TOKENS_OVERRIDE_FILE)))) continue;
    const override = parseCssCustomProperties(await fs.readFile(path.join(localRoot, 'design-systems', id, TOKENS_OVERRIDE_FILE), 'utf8'));
    const upstreamPath = path.join(targetRoot, 'design-systems', id, 'tokens.css');
    const upstream = (await pathExists(upstreamPath)) ? parseCssCustomProperties(await fs.readFile(upstreamPath, 'utf8')) : new Map();
    for (const [name, value] of override) {
      if (upstream.get(name)?.toLowerCase() === value.toLowerCase()) redundant.push(`${id}: ${name}`);
    }
  }
  for (const id of await listDirs(path.join(localRoot, 'design-systems'))) {
    const sectionsPath = path.join(localRoot, 'design-systems', id, DESIGN_SECTIONS_FILE);
    const designPath = path.join(targetRoot, 'design-systems', id, 'DESIGN.md');
    if (!(await pathExists(sectionsPath)) || !(await pathExists(designPath))) continue;
    const designMd = await fs.readFile(designPath, 'utf8');
    let applied;
    try {
      applied = applyDesignSections(designMd, await fs.readFile(sectionsPath, 'utf8'), id);
    } catch {
      continue; // an unknown heading is applyLocalOverlay's error to report
    }
    if (applied === designMd) redundant.push(`${id}: ${DESIGN_SECTIONS_FILE}`);
  }
  return redundant;
}

export async function applyLocalOverlay(targetRoot, localRoot = LOCAL_ROOT) {
  const skillIds = await listDirs(path.join(localRoot, 'skills'));
  const templateIds = new Set(await listDirs(path.join(targetRoot, 'design-templates')));

  const collisions = [];
  for (const id of skillIds) {
    if (templateIds.has(id)) {
      collisions.push(`${id} (upstream design-template)`);
      continue;
    }
    const dst = path.join(targetRoot, 'skills', id);
    if ((await pathExists(dst)) && !(await pathExists(path.join(dst, OVERLAY_MARKER)))) {
      collisions.push(`${id} (upstream skill)`);
    }
  }
  // Examples pair with a skill of the same id (as upstream's do), so they only collide with upstream examples.
  const exampleIds = await listDirs(path.join(localRoot, 'examples'));
  for (const id of exampleIds) {
    const dst = path.join(targetRoot, 'examples', id);
    if ((await pathExists(dst)) && !(await pathExists(path.join(dst, OVERLAY_MARKER)))) collisions.push(`${id} (upstream example)`);
  }
  const craftNames = await listLocalCraft(localRoot);
  const ourCraft = await previousCraftCopies(targetRoot);
  for (const name of craftNames) {
    if ((await pathExists(path.join(targetRoot, CRAFT_DIR, name))) && !ourCraft.has(name)) collisions.push(`${name.replace(/\.md$/, '')} (upstream craft doc)`);
  }
  if (collisions.length > 0) {
    throw new Error(
      `Local overlay id collision: ${collisions.join(', ')}. Rename the overlay entry under packages/content/local/skills/, local/examples/ or local/craft/ — overlay entries never shadow upstream ones.`,
    );
  }

  // local/design-systems/<id>/ is one of two shapes, disambiguated by its own
  // file set: an override (one or both of OVERRIDE_FILES) targets an EXISTING
  // upstream design system — the opposite of skills, which must NOT collide.
  // A new package (exactly NEW_DESIGN_SYSTEM_FILES) is the mirror of skills:
  // it must NOT already exist upstream. Anything else is ambiguous/malformed.
  const allDesignSystemIds = await listDirs(path.join(localRoot, 'design-systems'));
  const overrideIds = [];
  const newPackageIds = [];
  const designSystemProblems = [];
  for (const id of allDesignSystemIds) {
    const names = new Set(await listFiles(path.join(localRoot, 'design-systems', id)));
    const upstreamExists = await pathExists(path.join(targetRoot, 'design-systems', id, 'DESIGN.md'));
    if (isOverrideShape(names)) {
      if (!upstreamExists) designSystemProblems.push(`${id} (override of a non-existent upstream design system)`);
      else if (names.has(DESIGN_SECTIONS_FILE)) {
        // Every overlay section must name one the vendored DESIGN.md has.
        const designMd = await fs.readFile(path.join(targetRoot, 'design-systems', id, 'DESIGN.md'), 'utf8');
        const sectionsMd = await fs.readFile(path.join(localRoot, 'design-systems', id, DESIGN_SECTIONS_FILE), 'utf8');
        try {
          applyDesignSections(designMd, sectionsMd, id);
          if (splitSections(sectionsMd).sections.length === 0) designSystemProblems.push(`${id} (${DESIGN_SECTIONS_FILE} has no ## sections)`);
        } catch (err) {
          designSystemProblems.push(`${id} (${err.message.replace(`${id}: `, '')})`);
        }
      }
      overrideIds.push(id);
    } else if (NEW_DESIGN_SYSTEM_FILES.every((name) => names.has(name)) && names.size === NEW_DESIGN_SYSTEM_FILES.length) {
      const dst = path.join(targetRoot, 'design-systems', id);
      if (upstreamExists && !(await pathExists(path.join(dst, OVERLAY_MARKER)))) {
        designSystemProblems.push(`${id} (upstream design system already has this id)`);
      } else {
        newPackageIds.push(id);
      }
    } else {
      designSystemProblems.push(
        `${id} (must contain ${OVERRIDE_FILES.join(' and/or ')}, or exactly ${NEW_DESIGN_SYSTEM_FILES.join(', ')}; found: ${[...names].join(', ') || 'nothing'})`,
      );
    }
  }
  if (designSystemProblems.length > 0) {
    throw new Error(`Invalid design-system overlay entry: ${designSystemProblems.join(', ')}. See packages/content/local/README.md.`);
  }

  for (const id of skillIds) {
    const dst = path.join(targetRoot, 'skills', id);
    await fs.rm(dst, { recursive: true, force: true });
    await fs.cp(path.join(localRoot, 'skills', id), dst, { recursive: true });
    await fs.writeFile(path.join(dst, OVERLAY_MARKER), 'Copied from packages/content/local/ by apply-local-overlay.mjs. Do not edit here.\n');
  }

  for (const id of exampleIds) {
    const dst = path.join(targetRoot, 'examples', id);
    await fs.rm(dst, { recursive: true, force: true });
    await fs.cp(path.join(localRoot, 'examples', id), dst, { recursive: true });
    await fs.writeFile(path.join(dst, OVERLAY_MARKER), 'Copied from packages/content/local/ by apply-local-overlay.mjs. Do not edit here.\n');
  }

  // prompts/ has no upstream counterpart: wholly overlay-owned, so replaced outright.
  const promptsDst = path.join(targetRoot, 'prompts');
  await fs.rm(promptsDst, { recursive: true, force: true });
  const promptNames = await listFiles(path.join(localRoot, 'prompts'));
  if (promptNames.length > 0) {
    await fs.mkdir(promptsDst, { recursive: true });
    for (const name of promptNames) await fs.copyFile(path.join(localRoot, 'prompts', name), path.join(promptsDst, name));
  }

  // notices/ is overlay-owned too: shipped with the assets so every host that mirrors them carries the licences.
  const noticesDst = path.join(targetRoot, NOTICES_DIR);
  await fs.rm(noticesDst, { recursive: true, force: true });
  const noticeNames = await listFiles(path.join(localRoot, NOTICES_DIR));
  if (noticeNames.length > 0) {
    await fs.mkdir(noticesDst, { recursive: true });
    for (const name of noticeNames) await fs.copyFile(path.join(localRoot, NOTICES_DIR, name), path.join(noticesDst, name));
  }

  // Craft docs sit beside upstream's: drop our previous copies, then copy and record the current set.
  const craftDst = path.join(targetRoot, CRAFT_DIR);
  for (const name of ourCraft) await fs.rm(path.join(craftDst, name), { force: true });
  await fs.rm(path.join(craftDst, OVERLAY_MARKER), { force: true });
  if (craftNames.length > 0) {
    await fs.mkdir(craftDst, { recursive: true });
    for (const name of craftNames) await fs.copyFile(path.join(localRoot, CRAFT_DIR, name), path.join(craftDst, name));
    await fs.writeFile(
      path.join(craftDst, OVERLAY_MARKER),
      `Copied from packages/content/local/craft/ by apply-local-overlay.mjs. Do not edit here.\n${craftNames.join('\n')}\n`,
    );
  }
  if (await pathExists(path.join(localRoot, CRAFT_REQUIRES_FILE))) await fs.copyFile(path.join(localRoot, CRAFT_REQUIRES_FILE), path.join(targetRoot, CRAFT_REQUIRES_FILE));
  else await fs.rm(path.join(targetRoot, CRAFT_REQUIRES_FILE), { force: true });

  // surfaces.json has no upstream counterpart either: copied, or removed when local/ has none.
  // voice.md: the shared voice block local prompts include (openspec plain-language-replies).
  if (await pathExists(path.join(localRoot, VOICE_FILE))) await fs.copyFile(path.join(localRoot, VOICE_FILE), path.join(targetRoot, VOICE_FILE));
  else await fs.rm(path.join(targetRoot, VOICE_FILE), { force: true });
  if (await pathExists(path.join(localRoot, PRINT_HOUSES_FILE))) await fs.copyFile(path.join(localRoot, PRINT_HOUSES_FILE), path.join(targetRoot, PRINT_HOUSES_FILE));
  else await fs.rm(path.join(targetRoot, PRINT_HOUSES_FILE), { force: true });

  const hasSurfaces = await pathExists(path.join(localRoot, SURFACES_FILE));
  if (hasSurfaces) await fs.copyFile(path.join(localRoot, SURFACES_FILE), path.join(targetRoot, SURFACES_FILE));
  else await fs.rm(path.join(targetRoot, SURFACES_FILE), { force: true });

  // integrations.json likewise has no upstream counterpart.
  const hasIntegrations = await pathExists(path.join(localRoot, INTEGRATIONS_FILE));
  if (hasIntegrations) await fs.copyFile(path.join(localRoot, INTEGRATIONS_FILE), path.join(targetRoot, INTEGRATIONS_FILE));
  else await fs.rm(path.join(targetRoot, INTEGRATIONS_FILE), { force: true });

  // design-system-descriptors.json likewise has no upstream counterpart.
  const hasDescriptors = await pathExists(path.join(localRoot, DESCRIPTORS_FILE));
  if (hasDescriptors) await fs.copyFile(path.join(localRoot, DESCRIPTORS_FILE), path.join(targetRoot, DESCRIPTORS_FILE));
  else await fs.rm(path.join(targetRoot, DESCRIPTORS_FILE), { force: true });

  // gallery-site.json likewise has no upstream counterpart.
  if (await pathExists(path.join(localRoot, GALLERY_SITE_FILE))) await fs.copyFile(path.join(localRoot, GALLERY_SITE_FILE), path.join(targetRoot, GALLERY_SITE_FILE));
  else await fs.rm(path.join(targetRoot, GALLERY_SITE_FILE), { force: true });

  // Drop overrides from a previous run that local/ no longer has, so a
  // standalone re-apply after deleting one doesn't leave it in effect.
  const overrideIdSet = new Set(overrideIds);
  const newPackageIdSet = new Set(newPackageIds);
  for (const id of await listDirs(path.join(targetRoot, 'design-systems'))) {
    for (const name of OVERRIDE_FILES) {
      if (!overrideIdSet.has(id) || !(await pathExists(path.join(localRoot, 'design-systems', id, name)))) {
        await fs.rm(path.join(targetRoot, 'design-systems', id, name), { force: true });
      }
    }
    // A previously-overlaid new package that local/ no longer has: remove the
    // whole copied folder, but only ours to remove (OVERLAY_MARKER present) —
    // never a genuine upstream entry that happens to share the id.
    if (!newPackageIdSet.has(id)) {
      const dst = path.join(targetRoot, 'design-systems', id);
      if (await pathExists(path.join(dst, OVERLAY_MARKER))) await fs.rm(dst, { recursive: true, force: true });
    }
  }
  for (const id of overrideIds) {
    for (const name of OVERRIDE_FILES) {
      const src = path.join(localRoot, 'design-systems', id, name);
      if (await pathExists(src)) await fs.copyFile(src, path.join(targetRoot, 'design-systems', id, name));
    }
  }
  for (const id of newPackageIds) {
    const dst = path.join(targetRoot, 'design-systems', id);
    await fs.rm(dst, { recursive: true, force: true });
    await fs.cp(path.join(localRoot, 'design-systems', id), dst, { recursive: true });
    await fs.writeFile(path.join(dst, OVERLAY_MARKER), 'Copied from packages/content/local/ by apply-local-overlay.mjs. Do not edit here.\n');
  }

  const counts = {
    skills: skillIds.length,
    examples: exampleIds.length,
    prompts: promptNames.length,
    craft: craftNames.length,
    designSystemOverrides: overrideIds.length,
    designSystemPackages: newPackageIds.length,
  };
  const manifestPath = path.join(targetRoot, 'MANIFEST.json');
  if (await pathExists(manifestPath)) {
    const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'));
    manifest.localOverlay = counts;
    await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  }

  return counts;
}

const isMainModule = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMainModule) {
  const targetRoot = path.join(packageRoot, 'assets', 'open-design');
  applyLocalOverlay(targetRoot)
    .then(({ skills, examples, prompts, craft, designSystemOverrides, designSystemPackages }) =>
      console.log(
        `Applied local overlay: ${skills} skills, ${examples} examples, ${prompts} prompts, ${craft} craft docs, ${designSystemOverrides} design-system overrides, ${designSystemPackages} new design-system packages.`,
      ),
    )
    .catch((err) => {
      console.error(err.message ?? err);
      process.exit(1);
    });
}
